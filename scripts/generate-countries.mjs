/**
 * One-off generator: distills world-countries into a tiny static module so the
 * guest booking wizard does not ship the full 1.38 MB dataset.
 *
 * Names come from world-countries (they are stored as a guest's nationality,
 * so keep them stable). Dialling codes come from libphonenumber-js, which
 * follows the ITU country calling codes: world-countries' `idd` splits the
 * code from area prefixes ("+1" + "684"), and joining them gave wrong codes
 * such as "+1684" or "+35818". NANP countries are "+1"; the area code is part
 * of the number the guest types. Places with no calling code get "".
 *
 * Flags are left out on purpose: Windows renders flag emoji as two letters.
 *
 * world-countries is not a project dependency. Install it anywhere and point
 * NODE_PATH at it (libphonenumber-js resolves from this repo):
 *   npm i --prefix /tmp/gen world-countries@5
 *   NODE_PATH=/tmp/gen/node_modules node scripts/generate-countries.mjs
 * Output: lib/countries-data.ts
 */
import { createRequire } from "node:module";
import { writeFileSync } from "node:fs";

const require = createRequire(import.meta.url);
const countries = require("world-countries");
const { getCountryCallingCode, isSupportedCountry } = require("libphonenumber-js");

const list = countries
  .filter((c) => c.cca2 && c.name?.common)
  .map((c) => ({
    code: c.cca2,
    name: c.name.common,
    dialCode: isSupportedCountry(c.cca2) ? `+${getCountryCallingCode(c.cca2)}` : "",
  }));

list.sort((a, b) => {
  if (a.name === "Ghana") return -1;
  if (b.name === "Ghana") return 1;
  if (a.name === "Nigeria") return -1;
  if (b.name === "Nigeria") return 1;
  return a.name.localeCompare(b.name);
});

const out = `// AUTO-GENERATED by scripts/generate-countries.mjs — do not edit by hand.
// Trimmed country dataset (ISO code, name, ITU dialling code) for the booking
// forms. Regenerate with: node scripts/generate-countries.mjs

export interface CountryOption {
  /** ISO 3166-1 alpha-2. */
  code: string;
  name: string;
  /** "+233"; "" where the place has no country calling code. */
  dialCode: string;
}

export const COUNTRIES: CountryOption[] = ${JSON.stringify(list, null, 0)};
`;

writeFileSync("lib/countries-data.ts", out);
console.log(`Wrote lib/countries-data.ts with ${list.length} countries`);
