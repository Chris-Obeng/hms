import type { Metadata, Viewport } from "next";
import { Plus_Jakarta_Sans, Geist_Mono, Fraunces } from "next/font/google";
import { ToastProvider } from "@/components/toast-provider";
import { ClerkProvider } from "@clerk/nextjs";
import { TooltipProvider } from "@/components/ui/tooltip";
import { Providers } from "@/components/providers";
import { SpeedInsights } from '@vercel/speed-insights/next';
import { Analytics } from "@vercel/analytics/next"
import { LAUNCH_BACKGROUND, SPLASH_SCREENS } from "@/lib/brand/splash";
import "./globals.css";

const geistMono = Geist_Mono({
  subsets: ["latin"],
  variable: "--font-geist-mono",
  display: "swap",
  preload: false,
});

// Fraunces: display face for the landing page only (scoped via landing
// tokens). Variable font — weight comes from the wght axis, so we omit
// `weight` and request only the extra SOFT/WONK axes the CSS pins to 0.
// preload:false keeps builds fast when Google Fonts is unreachable.
const fraunces = Fraunces({
  subsets: ["latin"],
  axes: ["SOFT", "WONK"],
  variable: "--font-fraunces",
  display: "swap",
  preload: false,
});

const jakarta = Plus_Jakarta_Sans({
  subsets: ["latin"],
  weight: ["400", "500", "600", "700"],
  variable: "--font-jakarta",
  display: "swap",
  preload: false,
});

/** Clerk's start screens in RoomLine's voice (the rest stays Clerk's default copy). */
const clerkLocalization = {
  signIn: {
    start: {
      title: "Sign in to RoomLine",
      subtitle: "Welcome back. Your front desk is ready.",
    },
  },
  signUp: {
    start: {
      title: "Create your account",
      subtitle: "It takes less than a minute.",
    },
  },
};

export const metadata: Metadata = {
  title: {
    default: "RoomLine",
    template: "%s | RoomLine",
  },
  description: "Hotel management and direct booking platform for independent properties",
  applicationName: "RoomLine",
  appleWebApp: {
    capable: true,
    // The product is light-only, so the status bar text must stay dark (the
    // platform default). "black-translucent" painted white text over light
    // content on iOS home-screen installs.
    statusBarStyle: "default",
    title: "RoomLine",
    // One exact-size launch image per iPhone / iPad (generated by `pnpm icons`).
    startupImage: SPLASH_SCREENS.map(({ url, media }) => ({ url, media })),
  },
  formatDetection: {
    telephone: false,
  },
  // Next emits only `mobile-web-app-capable`; iOS before 17 also needs the
  // Apple-prefixed tag to open standalone and to use the startup images.
  other: { "apple-mobile-web-app-capable": "yes" },
  icons: {
    // favicon.ico for legacy and default /favicon.ico requests, SVG for every
    // current browser, a full-bleed PNG for iOS (which rounds corners itself).
    // All generated from lib/brand/mark.ts by `pnpm icons`.
    icon: [
      { url: "/favicon.ico", sizes: "48x48" },
      { url: "/icons/icon.svg", type: "image/svg+xml" },
    ],
    apple: { url: "/apple-touch-icon.png", sizes: "180x180", type: "image/png" },
  },
};

/**
 * Theme colour = the dashboard header (and the manifest's theme_color), so the
 * Android status bar and an installed window's title bar read as one surface
 * with the header. Brand pages (landing, account routes, invites) override it
 * with their own paper colour.
 *
 * `colorScheme: "light"` tells the browser the document does not support dark
 * mode, so scrollbars, form controls and the canvas stay light even when the
 * OS is in dark mode.
 */
export const viewport: Viewport = {
  width: "device-width",
  initialScale: 1,
  viewportFit: "cover",
  themeColor: LAUNCH_BACKGROUND,
  colorScheme: "light",
};

export default function RootLayout({
  children,
}: Readonly<{
  children: React.ReactNode;
}>) {
  return (
    <html
      lang="en"
      className={`${jakarta.variable} ${geistMono.variable} ${fraunces.variable} font-sans h-full antialiased`}
      suppressHydrationWarning
    >
      <body className="native-shell min-h-dvh flex flex-col font-sans">
        <ClerkProvider localization={clerkLocalization}>
          <Providers>
            <TooltipProvider>{children}
              <SpeedInsights />
              <Analytics />
            </TooltipProvider>
            <ToastProvider />
          </Providers>
        </ClerkProvider>
      </body>
    </html>
  );
}
